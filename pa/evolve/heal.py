"""Self-heal pipeline (docs/EVOLVE.md #12): diagnose -> eval fixture
-> approval-gated code_task.

PA_EVOLVE_SELF_HEAL (default OFF): a `fix`/`tool` item in `planned`
gets a reproducing eval fixture attached, then a code_task prompt —
plan + scrubbed incidents + fixture + hard rules — QUEUED THROUGH
THE NORMAL APPROVAL GATE. The owner approves "spend a coding turn",
never a deploy. With GitHub creds in env the prompt asks for a
draft PR; without them it asks for a branch+patch under
DATA_DIR/evolve/patches/ (path recorded on the item). Nothing here
merges, pulls, or runs the new code.
"""

import json
import logging
import os

from .. import approvals, chattools, db as dbmod
from ..logsetup import scrub_text
from ..util import now_iso
from . import changelog, incidents, items

log = logging.getLogger("pa.evolve.heal")

HEAL_SHAPES = {"fix", "tool"}

_RULES = (
    "Work on a NEW branch off the current tip. One concern only. "
    "Add/adjust tests for the fix. Do NOT touch protected paths "
    "(pa/approvals.py, pa/allowrules.py, pa/review.py, pa/vault.py, "
    "pa/credvault.py, pa/secretsbox.py, pa/passwords.py, pa/egress.py, "
    "pa/untrusted.py, owner auth in pa/discordbot.py, session/CSRF "
    "in pa/webapp.py, pa/evolve/policy.py, .github/workflows/, "
    "deploy/) — the owner reviews those by hand. Do NOT merge, do "
    "NOT deploy, do NOT print secrets.")


def _gh_available(env) -> bool:
    env = os.environ if env is None else env
    if env.get("GH_TOKEN") or env.get("GITHUB_TOKEN"):
        return True
    from shutil import which
    return which("gh", path=env.get("PATH")) is not None


def _fixture(item) -> dict:
    """A reproducing eval fixture attached to the item's artifacts —
    the coding turn must make it (and the suite) pass."""
    return {
        "id": f"evolve_{item['id']}",
        "prompt": item["title"][:200],
        "script": ['{"final": "ok"}'],
        "must_not_contain": (item.get("error") or "")[:80] or
                            "(never emitted)",
        "note": "generated by self-heal; extend script to reproduce"}


def _traces(conn, item) -> str:
    fp = item["incident_fingerprint"]
    if not fp:
        return ""
    rows = conn.execute(
        "SELECT summary, detail FROM incidents WHERE fingerprint=?"
        " ORDER BY id DESC LIMIT 3", (fp,)).fetchall()
    return "\n".join(f"- {r['summary']}\n  {r['detail'][:300]}"
                     for r in rows)


def build_prompt(conn, s, item, env=None) -> str:
    art = json.loads(item["artifacts"] or "{}")
    fx = art.get("eval_fixture") or _fixture(item)
    patch_dir = os.path.join(os.path.dirname(
        os.path.abspath(s.db_path)), "evolve", "patches")
    if _gh_available(env):
        deliver = ("Open a DRAFT PR against the current release "
                   "branch with the fix.")
    else:
        deliver = (f"No GitHub creds here — leave a branch plus a "
                   f"unified-diff patch file under {patch_dir}/ "
                   f"named item-{item['id']}.diff.")
    traces = _traces(conn, item)
    return scrub_text(
        "pal self-heal task (owner approved a coding turn — NOT a "
        "deploy).\n\n"
        f"ITEM: {item['title']}\nPLAN:\n{item['plan']}\n\n"
        f"KNOWN TRACES:\n{traces or '(none)'}\n\n"
        f"EVAL FIXTURE TO REPRODUCE:\n{json.dumps(fx, indent=1)}\n\n"
        f"DELIVERABLE: {deliver}\n\nRULES: {_RULES}")[:6000]


def maybe_heal(conn, s, item_id, bot=None, ctx=None, env=None) -> str:
    """Advance a planned fix/tool item to building. Returns the
    status. Never raises."""
    try:
        if not s.evolve_self_heal:
            return "off"
        item = items.get(conn, item_id)
        if item is None or item["shape"] not in HEAL_SHAPES \
                or item["status"] != "planned":
            return item["status"] if item else "gone"
        art = json.loads(item["artifacts"] or "{}")
        if "eval_fixture" not in art:
            art["eval_fixture"] = _fixture(item)
        if not _gh_available(env):
            patch_dir = os.path.join(os.path.dirname(
                os.path.abspath(s.db_path)), "evolve", "patches")
            os.makedirs(patch_dir, exist_ok=True)
            art["patch_path"] = os.path.join(
                patch_dir, f"item-{item_id}.diff")
        prompt = build_prompt(conn, s, item, env=env)
        items.set_status(conn, item_id, "building", artifacts=art)
        if ctx is not None:
            out = chattools.run(ctx, "code_task",
                                {"prompt": prompt})
            if out.get("task_id"):
                art["task_id"] = out["task_id"]
                items.set_status(conn, item_id, "building",
                                 artifacts=art)
            else:
                items.set_status(
                    conn, item_id, "awaiting_approval",
                    artifacts={**art,
                               "gate": out.get("message", "")[:200]})
            changelog.log_event(conn, s, item_id, "building",
                                f"code_task {out.get('task_id') or 'held'}")
            return "building" if out.get("task_id") else \
                "awaiting_approval"
        # unattended path: job_action approval the owner clicks to
        # spend a coding turn (chatappr buttons run _code_task once)
        aid = approvals.create_approval(
            conn, "job_action",
            {"tool": "code_task", "args": {"prompt": prompt},
             "channel_id": "", "evolve_item": item_id})
        items.set_status(conn, item_id, "awaiting_approval",
                         artifacts={**art, "approval_id": aid})
        if bot is not None:
            try:
                dm = bot._owner_dm_id()
                if dm:
                    bot.api.post_message(
                        dm,
                        f"🩹 self-heal #{item_id}: spend a coding turn "
                        f"on\n{item['title']}\n(approve = queue a "
                        f"code_task; nothing deploys)",
                        components=[[
                            {"type": 2, "style": 3, "label": "Approve",
                             "custom_id": f"chatappr:{aid}:y"},
                            {"type": 2, "style": 4, "label": "Reject",
                             "custom_id": f"chatappr:{aid}:n"}]])
            except Exception:
                log.info("self-heal card failed", exc_info=True)
        changelog.log_event(conn, s, item_id, "awaiting_approval",
                            "self-heal card posted")
        return "awaiting_approval"
    except Exception:
        log.warning("maybe_heal failed", exc_info=True)
        return "error"


def incident_summary(conn, fingerprint, limit=3):
    return _traces(conn, {"incident_fingerprint": fingerprint})
