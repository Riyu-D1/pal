#!/usr/bin/env python3
"""Regenerate the env-var tables in docs/CONFIG.md from .env.example
and check that every name pa/config.py reads is documented.

    python3 scripts/gen_config_docs.py           # rewrite CONFIG.md
    python3 scripts/gen_config_docs.py --check   # fail on drift/coverage

.env.example is the edited source: `# --- title ---` lines start a
section, `# VAR=value` documents a commented-out option, `VAR=value`
an active default. pa/config.py stays the runtime source of truth —
the --check coverage pass reads its env lookups via the AST so a new
knob without a docs entry fails CI.
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXAMPLE = ROOT / ".env.example"
CONFIG_MD = ROOT / "docs" / "CONFIG.md"
CONFIG_PY = ROOT / "pa" / "config.py"

MARKER = "<!-- generated by scripts/gen_config_docs.py — edit .env.example, then re-run it -->"

# The minimal set AGENTS.md/setup.sh require — flagged in the table.
REQUIRED = {"DISCORD_BOT_TOKEN", "DISCORD_OWNER_ID",
            "LLM_BASE_URL", "LLM_MODEL", "LLM_API_KEY"}

# Constructed names (f-strings/format) that the AST cannot resolve —
# documented in .env.example prose as patterns. Each regex must match
# literal text in .env.example.
DYNAMIC_PATTERNS = [
    r"PA_NODE_<NAME>_TOKEN",
    r"PA_VISION_MODEL_<BACKEND>",
    r"PA_BUDGET_<RESOURCE>_<SCOPE>",
    r"PA_TTS_CHARS_<PROVIDER>_DAY",
    r"PA_ROUTER_CAP_<BACKEND>_<RPM\|TPM\|RPD\|TPD>",
]

SECTION_RE = re.compile(r"^#\s*-{3,}\s*(.*?)\s*-{3,}\s*$")
VAR_RE = re.compile(r"\b([A-Z][A-Z0-9_]*)=([^\s#]*)")


def _desc(parts: list[str]) -> str:
    text = " ".join(p for p in parts if p).strip()
    text = re.sub(r"\s+", " ", text)
    return text.replace("|", r"\|").replace("<", "&lt;").replace(">", "&gt;")


PATTERN_RE = re.compile(r"^([A-Z][A-Z0-9_<>|]*[A-Z0-9_>|])")


def parse_example(text: str):
    """-> [(section, [(var, active, value, desc), ...]), ...]"""
    sections: list[tuple[str, list]] = [("core", [])]
    pending: list[str] = []
    seen: set[str] = set()  # a var documented twice keeps its first row
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line:
            pending = []
            continue
        m = SECTION_RE.match(line)
        if m:
            sections.append((m.group(1), []))
            pending = []
            continue
        commented = line.lstrip().startswith("#")
        body = line.lstrip()[1:].lstrip() if commented else line
        # inline comment: '#' at start-of-value or after whitespace
        cut = re.search(r"(?<=[=\s])#|^\s*#", body)
        vars_part, inline = (body[:cut.start()], body[cut.end():]) \
            if cut else (body, "")
        first = vars_part.split(None, 1)
        token = first[0] if first else ""
        rest = first[1] if len(first) > 1 else ""
        if commented and "<" in token and PATTERN_RE.match(token):
            # dynamic family placeholder line: PA_NODE_<NAME>_TOKEN etc.
            name, _, val = token.partition("=")
            desc = _desc(pending + [val, rest, inline])
            sections[-1][1].append((name.rstrip("="), False, "", desc))
            pending = []
        elif re.match(r"[A-Z][A-Z0-9_]*=", vars_part):
            # a var line must START with VAR= — VAR= mid-prose is just a
            # mention inside a comment (examples, systemd hints)
            desc = _desc(pending + [inline])
            for name, value in VAR_RE.findall(vars_part):
                if name not in seen:
                    seen.add(name)
                    sections[-1][1].append((name, not commented, value, desc))
            pending = []
        elif commented:
            note = body.strip()
            if note:
                pending.append(note)
    return [(s, rows) for s, rows in sections if rows]


def env_names_config_py() -> set[str]:
    """Literal env names pa/config.py reads (dynamic families excluded)."""
    tree = ast.parse(CONFIG_PY.read_text(), filename=str(CONFIG_PY))
    consts: dict[str, str] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant) \
                and isinstance(node.value.value, str):
            for t in node.targets:
                if isinstance(t, ast.Name) and re.fullmatch(r"[A-Z][A-Z0-9_]+", t.id):
                    consts[t.id] = node.value.value

    def name_of(node) -> str | None:
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            return node.value
        if isinstance(node, ast.Name) and node.id in consts:
            return consts[node.id]
        return None

    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) \
                and node.func.attr == "get" and node.args:
            # env.get("X") / os.environ.get("X") — a bare `environ` name
            # is the WSGI request dict (headers), not env config.
            f = node.func.value
            if (isinstance(f, ast.Name) and f.id == "env") or \
               (isinstance(f, ast.Attribute) and f.attr == "environ"):
                n = name_of(node.args[0])
                if n:
                    names.add(n)
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Name) \
                and node.func.id in ("_bool", "_int", "_float") and len(node.args) >= 2:
            n = name_of(node.args[1])
            if n:
                names.add(n)
        elif isinstance(node, ast.Subscript):
            f = node.value
            is_env = (isinstance(f, ast.Name) and f.id == "env") or \
                     (isinstance(f, ast.Attribute) and f.attr == "environ")
            n = name_of(node.slice)
            if is_env and n:
                names.add(n)
    return {n for n in names if re.fullmatch(r"[A-Z][A-Z0-9_]+", n)}


def render(sections) -> str:
    out = [MARKER, ""]
    for title, rows in sections:
        out += [f"## {title}", "",
                "| var | default | what it does |", "|---|---|---|"]
        for name, active, value, desc in rows:
            var = f"`{name.replace('|', chr(92) + '|')}`" + \
                (" **required**" if name in REQUIRED else "")
            default = value if (active and value) else "*(unset)*"
            out.append(f"| {var} | {default} | {desc} |")
        out.append("")
    return "\n".join(out)


def splice(generated: str) -> str:
    old = CONFIG_MD.read_text()
    if MARKER in old:
        head = old.split(MARKER, 1)[0]
    else:  # first generation: keep the hand-written intro above ## core
        m = re.search(r"^## ", old, re.M)
        head = old[:m.start()] if m else old.rstrip() + "\n\n"
    return head.rstrip() + "\n\n" + generated


def check(sections, generated) -> int:
    rc = 0
    documented = {name for _s, rows in sections for name, *_ in rows}
    missing = sorted(env_names_config_py() - documented)
    if missing:
        print("config.py reads env vars missing from .env.example:")
        for n in missing:
            print(f"  {n}")
        rc = 1
    example_text = EXAMPLE.read_text()
    for pat in DYNAMIC_PATTERNS:
        if not re.search(pat, example_text):
            print(f"dynamic family not documented in .env.example: {pat}")
            rc = 1
    if splice(generated) != CONFIG_MD.read_text():
        print("docs/CONFIG.md is stale — run scripts/gen_config_docs.py")
        rc = 1
    return rc


def main() -> int:
    sections = parse_example(EXAMPLE.read_text())
    generated = render(sections)
    if "--check" in sys.argv[1:]:
        return check(sections, generated)
    CONFIG_MD.write_text(splice(generated))
    print(f"wrote {CONFIG_MD.relative_to(ROOT)} "
          f"({sum(len(r) for _s, r in sections)} vars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
