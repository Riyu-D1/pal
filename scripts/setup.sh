#!/usr/bin/env bash
# pal one-command setup — works for a human or an AI agent.
#
#   scripts/setup.sh             # interactive: asks for the 3 required
#                                # values it can't invent, writes .env
#   scripts/setup.sh --check     # verify only, change nothing
#   scripts/setup.sh --non-interactive
#       reads the same values from env vars instead of prompting:
#       DISCORD_BOT_TOKEN, DISCORD_OWNER_ID,
#       LLM_BASE_URL, LLM_MODEL, LLM_API_KEY   (or PA_ROUTER_ENABLED=true
#                                               + a free backend key)
#
# Everything else is optional — copy .env.example blocks over later.
# This script never prints secret values and never commits .env.
set -euo pipefail
cd "$(dirname "$0")/.."

CHECK_ONLY=0
NON_INTERACTIVE=0
for arg in "$@"; do
  case "$arg" in
    --check) CHECK_ONLY=1 ;;
    --non-interactive|--yes|-y) NON_INTERACTIVE=1 ;;
    -h|--help) sed -n '1,15p' "$0"; exit 0 ;;
    *) echo "unknown flag: $arg (see --help)" >&2; exit 2 ;;
  esac
done

say()  { printf '\033[1m==>\033[0m %s\n' "$*"; }
warn() { printf '  \033[33mwarn\033[0m %s\n' "$*"; }
die()  { printf '\033[31merror\033[0m %s\n' "$*" >&2; exit 1; }

PY=.venv/bin/python

# --- 1. python + venv -------------------------------------------------
if [ ! -x "$PY" ]; then
  [ "$CHECK_ONLY" = 1 ] && die "no .venv — run scripts/setup.sh"
  PYBIN="$(command -v python3.12 || command -v python3 || true)"
  [ -n "$PYBIN" ] || die "python3 not found — install Python 3.11+"
  say "creating .venv ($PYBIN)"
  "$PYBIN" -m venv .venv
fi
V="$("$PY" -c 'import sys;print("%d.%d"%sys.version_info[:2])')"
case "$V" in 3.1[1-9]*|3.[2-9]*) ;; *) die "python $V too old — need >= 3.11";; esac
say "python $V"

if ! "$PY" -c 'import waitress, cryptography, pypdf' 2>/dev/null; then
  [ "$CHECK_ONLY" = 1 ] && die "deps missing in .venv — run scripts/setup.sh"
  say "installing requirements.txt"
  "$PY" -m pip install -q -r requirements.txt
fi
say "deps ok"

# --- 2. .env -----------------------------------------------------------
have_env() { grep -qE "^$1=.+" .env 2>/dev/null; }

if [ "$CHECK_ONLY" = 1 ]; then
  [ -f .env ] || die "no .env — run scripts/setup.sh (or cp .env.example .env)"
else
  if [ ! -f .env ]; then
    say "creating .env from .env.example (comments trimmed)"
    { echo "# pal env — generated by scripts/setup.sh"
      echo "# full reference: .env.example / docs/CONFIG.md"
      echo "PA_ENV=production"
      echo "PA_DATA_DIR=./data"
      echo "PA_BIND=127.0.0.1"
      echo "PA_PORT=8080"
      echo "PA_TIMEZONE=Europe/London"
      echo "DISCORD_ENABLED=true"; } > .env
    chmod 600 .env
  fi

  # collect the three things we cannot invent. env vars win; then prompt.
  ask() { # ask VAR "prompt" [required]
    local var="$1" prompt="$2" req="${3:-1}" val=""
    val="$(printenv "$var" 2>/dev/null || true)"
    if [ -z "$val" ] && have_env "$var"; then return 0; fi
    if [ -z "$val" ]; then
      if [ "$NON_INTERACTIVE" = 1 ]; then
        [ "$req" = 1 ] && warn "$var unset (non-interactive; setup.sh --check will flag it)"
        return 0
      fi
      printf '  %s: ' "$prompt"
      IFS= read -r val || true
    fi
    [ -z "$val" ] && return 0
    grep -v "^$var=" .env > .env.tmp && mv .env.tmp .env
    printf '%s=%s\n' "$var" "$val" >> .env
    chmod 600 .env
  }

  if [ "$NON_INTERACTIVE" = 0 ] && [ ! -t 0 ]; then NON_INTERACTIVE=1; fi
  say "required values (env vars override prompts; empty keeps current)"
  ask DISCORD_BOT_TOKEN  "Discord bot token (dev portal → Bot)"
  ask DISCORD_OWNER_ID   "your Discord user id (developer mode → copy id)"

  if ! have_env LLM_BASE_URL && [ -z "${PA_ROUTER_ENABLED:-}" ]; then
    echo "  model endpoint — pick ONE:"
    echo "   a) free Groq key  : https://api.groq.com/openai/v1 (+ LLM_MODEL, LLM_API_KEY)"
    echo "   b) free router    : PA_ROUTER_ENABLED=true + GROQ_API_KEY=..."
    echo "   c) any OpenAI-compatible endpoint you have"
    ask LLM_BASE_URL "LLM_BASE_URL (blank = configure later)" 0
    ask LLM_MODEL    "LLM_MODEL" 0
    ask LLM_API_KEY  "LLM_API_KEY (blank for anonymous endpoints)" 0
  fi
fi

# --- 3. migrate + doctor ----------------------------------------------
set -a; . ./.env 2>/dev/null || true; set +a
say "migrating database"
"$PY" -m pa migrate >/dev/null
say "doctor"
"$PY" -m pa doctor || RC=$?
RC=${RC:-0}

if [ "$CHECK_ONLY" = 0 ] && [ "$RC" = 0 ]; then
  cat <<'NEXT'

next (pal does NOT read .env by itself — load it into your shell first):
  0. . .venv/bin/activate && set -a && . ./.env && set +a
  1. python -m pa create-owner     # web-UI login (username+password)
  2. python -m pa serve            # http://127.0.0.1:8080 + Discord bot
  3. curl http://127.0.0.1:8080/healthz
  4. DM the bot on Discord, or: python -m pa chat "hello"

optional: /connect google for Gmail+Calendar, VAULT_PATH for notes,
PA_ROUTER_ENABLED for free-API failover — docs/SETUP.md, docs/CONFIG.md
NEXT
fi
exit "$RC"
